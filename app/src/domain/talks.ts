const normalize = (value: string) =>
  value
    .replace(/[ً-ْـ]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .toLowerCase();

export type TalkSuggestion = { talk: Talk; reasons: string[]; score: number; used: boolean };

/**
 * ترتيب المواضيع: المرتبط بالملاحظات والمخالفات المفتوحة أولًا، ثم موسم الصيف للإجهاد الحراري،
 * والمواضيع اللي انقالت هالسنة (عنوان اجتماع بنفس الاسم) تنزل لآخر القائمة.
 */
export function suggestTalks(ws: Workspace, today: string): TalkSuggestion[] {
  const month = Number(today.slice(5, 7));
  const summer = month >= 5 && month <= 9;
  const open = (ws.findings ?? []).filter((item) => item.status !== 'closed').map((item) => normalize(item.title + ' ' + item.description));
  const usedTitles = new Set(yearMeetings(ws, Number(today.slice(0, 4))).map((m) => normalize(m.title)));
  return TALKS.map((talk, index) => {
    const reasons: string[] = [];
    let score = -index / 100; // ترتيب المكتبة يكسر التعادل
    const related = open.filter((text) => talk.keywords.some((word) => text.includes(normalize(word)))).length;
    if (related) {
      score += 3 * related;
      reasons.push('مرتبط بـ ' + related + (related === 1 ? ' ملاحظة مفتوحة' : ' ملاحظات مفتوحة'));
    }
    if (talk.summer && summer) {
      score += 2;
      reasons.push('موسم الحر');
    }
    const used = usedTitles.has(normalize(talk.title));
    if (used) score -= 10;
    else reasons.push('ما انقال هالسنة');
    return { talk, reasons, score, used };
  }).sort((a, b) => b.score - a.score);
}

/** نص قصير جاهز للمشاركة في القروبات. */
export function talkText(talk: Talk): string {
  return ['🦺 ' + talk.title, '', ...talk.points.map((point) => '• ' + point), '', '❓ ' + talk.question].join('\n');
}
